// Copies the website's page renderers into src/site-preview/website so the admin's Live Preview
// renders drafts with the real website code, without the website running anywhere.
//
//   npm run sync-preview                      (website at ../taxalphonic-dynamic-frontend)
//   SITE_SOURCE_DIR=/path/to/website npm run sync-preview
//
// Run it after changing the website's blocks or their CSS. It starts from ENTRIES, follows every
// "@/..." and relative import, and copies those files unchanged. Next.js-only modules
// (next/*, the server-side apiClient and the form Server Action) are not copied: the preview
// Vite plugin (src/site-preview/vitePlugin.js) swaps them for browser shims.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const adminDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const siteDir = path.resolve(adminDir, process.env.SITE_SOURCE_DIR || '../taxalphonic-dynamic-frontend');
const outDir = path.join(adminDir, 'src/site-preview/website');

const ENTRIES = [
  'service/servicePreview.js',
  'components/tax-alphonic/pages/ApiServicePage.jsx',
  'components/tax-alphonic/pages/ApiPage.jsx',
  'components/tax-alphonic/home/HomeSections.jsx',
];
// Replaced by shims in src/site-preview/shims.
const SHIMMED = new Set(['service/apiClient.js', 'service/formSubmission.js']);
const GLOBAL_CSS = 'app/globals.css';

if (!fs.existsSync(path.join(siteDir, 'package.json'))) {
  console.error(`Website not found at ${siteDir}. Set SITE_SOURCE_DIR to the website folder.`);
  process.exit(1);
}

const toPosix = (p) => p.split(path.sep).join('/');
const files = [];
const cssFiles = [];
const seen = new Set();

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith('@/')) base = spec.slice(2);
  else if (spec.startsWith('.')) base = toPosix(path.normalize(path.join(path.dirname(from), spec)));
  else return null; // package or next/* (shimmed)
  for (const ext of ['', '.js', '.jsx', '/index.js', '/index.jsx']) {
    const candidate = base + ext;
    const full = path.join(siteDir, candidate);
    if (fs.existsSync(full) && fs.statSync(full).isFile()) return candidate;
  }
  throw new Error(`Cannot resolve "${spec}" imported from ${from}`);
}

function walk(file) {
  if (seen.has(file) || SHIMMED.has(file)) return;
  seen.add(file);
  if (file.endsWith('.css')) {
    cssFiles.push(file);
    return;
  }
  files.push(file);
  const source = fs.readFileSync(path.join(siteDir, file), 'utf8');
  const re = /(?:import|export)[^'"]*?from\s*['"]([^'"]+)['"]|import\s*['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;
  for (const match of source.matchAll(re)) {
    const target = resolveImport(file, match[1] || match[2] || match[3]);
    if (target) walk(target);
  }
}

ENTRIES.forEach(walk);

fs.rmSync(outDir, { recursive: true, force: true });
const copy = (file, transform = (s) => s) => {
  const dest = path.join(outDir, file);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, transform(fs.readFileSync(path.join(siteDir, file), 'utf8')));
};

files.forEach((file) => copy(file));
cssFiles.forEach((file) => copy(file));
// Tailwind scans only the copied website files, not the admin.
copy(GLOBAL_CSS, (css) => css.replace(/@import\s+["']tailwindcss["']\s*;/, '@import "tailwindcss" source("../");'));

// Stylesheets in the order the website loads them: globals (layout) first, then the blocks' CSS.
const styleFiles = [GLOBAL_CSS, ...cssFiles];
fs.writeFileSync(
  path.join(outDir, 'styles.js'),
  '// Generated by scripts/sync-site-preview.mjs. Do not edit.\n'
    + styleFiles.map((file, i) => `import css${i} from './${file}?inline';`).join('\n')
    + `\n\nexport default [${styleFiles.map((_, i) => `css${i}`).join(', ')}];\n`
);
fs.writeFileSync(
  path.join(outDir, 'SYNCED.md'),
  `# Copied from the website. Do not edit here.\n\nEdit the website (${toPosix(path.relative(adminDir, siteDir))}) and run \`npm run sync-preview\`.\n\nLast sync: ${new Date().toISOString()}\n\n${[...files, ...styleFiles].map((f) => `- ${f}`).join('\n')}\n`
);

console.log(`Copied ${files.length} modules and ${styleFiles.length} stylesheets from ${siteDir}`);
